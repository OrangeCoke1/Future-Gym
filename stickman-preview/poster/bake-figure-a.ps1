# Regenerates the baked figures used by the posters from male_body.glb:
#   figure-a.js  (posters A, D)      : bake-figure-a.ps1
#   figures.js   (posters E-I poses) : bake-figure-a.ps1 -Page bake-figures.html -Out figures.js -Var FIGS
# Needs the local server running (start.bat, port 8000) and Microsoft Edge or Chrome.
param([int]$Port = 8000, [string]$Page = 'bake-figure-a.html', [string]$Out = 'figure-a.js', [string]$Var = 'FIG_A')
$ErrorActionPreference = 'Stop'
$browser = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe", "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
  "$env:ProgramFiles\Google\Chrome\Application\chrome.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $browser) { throw 'Edge / Chrome not found' }
$profileDir = Join-Path $env:TEMP ('bake-figure-a-' + [guid]::NewGuid())
$dom = & $browser --headless=new --use-angle=swiftshader --enable-unsafe-swiftshader --user-data-dir="$profileDir" --virtual-time-budget=15000 --dump-dom "http://localhost:$Port/poster/$Page" | Out-String
Remove-Item -LiteralPath $profileDir -Recurse -Force -ErrorAction SilentlyContinue
$m = [regex]::Match($dom, '<pre id="out">(\{.*?\})</pre>', 'Singleline')
if (-not $m.Success) { throw "bake failed: $($dom.Substring(0, [Math]::Min(400, $dom.Length)))" }
$json = [System.Net.WebUtility]::HtmlDecode($m.Groups[1].Value)
$out = Join-Path $PSScriptRoot $Out
$text = "// Generated by bake-figure-a.ps1 from $Page and male_body.glb (`"Male Body`" by Alexander Antipov, CC BY 4.0). Do not edit by hand.`n" +
  "// Shading of the model (grey = light, alpha = body) plus anchor points.`n" +
  "window.$Var = $json;`n"
[IO.File]::WriteAllText($out, $text, (New-Object System.Text.UTF8Encoding($false)))
"wrote $out ($((Get-Item $out).Length) bytes)"
